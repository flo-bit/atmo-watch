import { DatabaseSync } from 'node:sqlite';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { getDialect, recordsTableName, type Database } from '@atmo-dev/contrail';
import { communityPresenceResponse } from './community-presence';

let sqlite: DatabaseSync;
let db: Database;
let queries: { sql: string; bindings: unknown[] }[];

beforeEach(() => {
	sqlite = new DatabaseSync(':memory:');
	queries = [];
	db = {
		prepare: vi.fn((sql: string) => ({
			bind: (...bindings: unknown[]) => ({
				first: async () => {
					queries.push({ sql, bindings });
					return sqlite.prepare(sql).get(...(bindings as string[]));
				}
			})
		}))
	} as unknown as Database;
	const dialect = getDialect(db);
	for (const collection of ['review', 'video']) {
		const table = recordsTableName(collection);
		sqlite.exec(`CREATE TABLE ${table} (cid TEXT, record TEXT)`);
		// Match the expression indexes already generated by Contrail's queryable config.
		for (const field of ['creativeWorkType', 'identifiers.tmdbId', 'identifiers.tmdbTvSeriesId']) {
			const name = `${collection}_${field.replaceAll('.', '_')}`;
			sqlite.exec(`CREATE INDEX ${name} ON ${table} (${dialect.jsonExtract('record', field)})`);
		}
	}
});

afterEach(() => sqlite.close());

function insert(collection: string, value: unknown, cid: string | null = 'cid') {
	sqlite
		.prepare(`INSERT INTO ${recordsTableName(collection)} (cid, record) VALUES (?, ?)`)
		.run(cid, value === null ? null : JSON.stringify(value));
}

async function presence(type = 'movie', id = '123') {
	return communityPresenceResponse(db, new URLSearchParams({ creativeWorkType: type, tmdbId: id }));
}

describe('indexed community presence', () => {
	it('returns empty flags in one bounded query, without HTTP caching', async () => {
		const response = await presence();
		expect(await response.json()).toEqual({
			hasReviews: false,
			hasVideos: false,
			hasDescendantVideos: false
		});
		expect(queries).toHaveLength(1);
		expect(response.headers.get('Cache-Control')).toBe('no-store');
		expect(queries[0].sql).not.toMatch(/COUNT|AVG|ORDER BY|profiles/i);
	});

	it('counts rating-only and text-only reviews, separates IDs/types and ignores tombstones', async () => {
		insert('review', { creativeWorkType: 'movie', identifiers: { tmdbId: '123' }, rating: 0 });
		insert('review', {
			creativeWorkType: 'tv_show',
			identifiers: { tmdbId: '456' },
			text: 'Review'
		});
		insert('review', { creativeWorkType: 'movie', identifiers: { tmdbId: '789' } }, null);
		insert('review', null);
		expect(await (await presence()).json()).toMatchObject({ hasReviews: true });
		expect(await (await presence('tv_show')).json()).toMatchObject({ hasReviews: false });
		expect(await (await presence('tv_show', '456')).json()).toMatchObject({ hasReviews: true });
		expect(await (await presence('movie', '789')).json()).toMatchObject({ hasReviews: false });
	});

	it('finds TV descendants even when the show has no exact-title videos', async () => {
		insert('video', {
			creativeWorkType: 'tv_episode',
			identifiers: { tmdbId: '999', tmdbTvSeriesId: '123', seasonNumber: 0 }
		});
		expect(await (await presence('tv_show')).json()).toEqual({
			hasReviews: false,
			hasVideos: false,
			hasDescendantVideos: true
		});
		expect(await (await presence('movie')).json()).toMatchObject({ hasDescendantVideos: false });
	});

	it('finds exact videos, then reflects deletions', async () => {
		insert('video', { creativeWorkType: 'movie', identifiers: { tmdbId: '123' } });
		expect(await (await presence()).json()).toMatchObject({ hasVideos: true });
		expect(await (await presence('tv_show')).json()).toMatchObject({ hasVideos: false });
		sqlite.exec(`UPDATE ${recordsTableName('video')} SET cid = NULL`);
		expect(await (await presence()).json()).toMatchObject({ hasVideos: false });
	});

	it('uses identifier expression indexes for all three TV probes', async () => {
		await presence('tv_show');
		const { sql, bindings } = queries[0];
		const plan = sqlite.prepare(`EXPLAIN QUERY PLAN ${sql}`).all(...(bindings as string[]));
		const searches = plan
			.map((row) => row.detail)
			.filter((detail) => String(detail).includes('SEARCH'));
		expect(searches).toHaveLength(3);
		expect(searches.join('\n')).toContain('review_identifiers_tmdbId');
		expect(searches.join('\n')).toContain('video_identifiers_tmdbId');
		expect(searches.join('\n')).toContain('video_identifiers_tmdbTvSeriesId');
	});

	it.each(['', '0', '-1', '1.5', '1e3', 'NaN', '9007199254740992', '1'.repeat(1000)])(
		'rejects invalid/unbounded ID %s before querying',
		async (id) => {
			expect((await presence('movie', id)).status).toBe(400);
			expect(db.prepare).not.toHaveBeenCalled();
		}
	);

	it('rejects unsupported media types before querying', async () => {
		expect((await presence('tv_episode')).status).toBe(400);
		expect(db.prepare).not.toHaveBeenCalled();
	});
});
