import { spawn } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import { selectContrail } from './select-contrail.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const endpoint = 'https://api.atmo.watch';
const clientPath = path.join(root, 'src/lib/contrail/index.ts');
const lockPath = path.join(root, 'contrail.lock.json');
const prodTargetPath = path.join(root, 'src/lib/contrail-targets/prod.ts');

function run(command, args) {
	return new Promise((resolve, reject) => {
		const child = spawn(command, args, { cwd: root, stdio: 'inherit' });
		child.once('error', reject);
		child.once('exit', (code, signal) => {
			if (code === 0) resolve();
			else reject(new Error(`${command} exited with ${signal ?? `code ${code}`}`));
		});
	});
}

const contrailBin = path.join(
	root,
	'node_modules/.bin',
	process.platform === 'win32' ? 'contrail.cmd' : 'contrail'
);

const sourceLock = JSON.parse(await readFile(lockPath, 'utf8'));
const discoveryResponse = await fetch(`${endpoint}/.well-known/contrail`);
if (!discoveryResponse.ok) {
	throw new Error(`Could not read the production Contrail manifest (${discoveryResponse.status})`);
}
const discovery = await discoveryResponse.json();
if (discovery.contract?.digest !== sourceLock.contractDigest) {
	throw new Error(
		`Production still advertises ${discovery.contract?.digest ?? 'no contract digest'}, but the source contract is ${sourceLock.contractDigest}. Deploy the API first.`
	);
}

await run(contrailBin, [
	'connect',
	endpoint,
	'--root',
	root,
	'--out',
	'src/lib/contrail/lexicons',
	'--lock',
	'contrail.lock.json',
	'--client',
	'src/lib/contrail/index.ts',
	'--client-types',
	'src/lib/contrail/types/index.ts',
	'--update'
]);

const lock = JSON.parse(await readFile(lockPath, 'utf8'));
const protectedMethods = (lock.serviceAuth?.methods ?? []).map((method) => method.id);
const methods = [...new Set([...lock.methods, ...protectedMethods])].sort();
let client = await readFile(clientPath, 'utf8');
client = client
	.replace(
		'// Generated by `contrail connect`. Re-run the command to update; do not edit.',
		'// Generated from the deployed Contrail contract by scripts/update-prod-contrail.mjs.'
	)
	.replace(
		'import type {} from "./types/index.js";',
		"import type {} from '$lib/contrail/types/index.js';"
	)
	.replace(
		'export const contrail = createPublicServiceClient({',
		`export const contrailMethods = ${JSON.stringify(methods, null, '\t')} as const;\n\nexport const contrail = createPublicServiceClient({`
	);

await writeFile(prodTargetPath, await format(client, { filepath: prodTargetPath }));
await selectContrail('prod');
console.log(`Updated tracked production Contrail contract from ${endpoint}`);
