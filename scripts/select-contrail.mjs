import { spawn } from 'node:child_process';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const activeDir = path.join(root, 'src/lib/contrail-active');
const localConsumerRoot = path.join(root, '.contrail/local-consumer');
const localLockPath = path.join(localConsumerRoot, 'contrail.lock.json');
const localClientPath = path.join(localConsumerRoot, 'index.ts');
const defaultLocalEndpoint = 'http://127.0.0.1:8787';

function normalizeEndpoint(value) {
	return value.replace(/\/$/, '');
}

async function writeActiveModule(content, target) {
	await rm(activeDir, { recursive: true, force: true });
	await mkdir(activeDir, { recursive: true });
	await writeFile(path.join(activeDir, 'index.ts'), content);
	await mkdir(path.join(root, '.contrail'), { recursive: true });
	await writeFile(path.join(root, '.contrail/active-target'), `${target}\n`);
}

async function selectProd() {
	await writeActiveModule(
		`// Generated by scripts/select-contrail.mjs. Do not edit.\nexport { contrail, contrailMethods } from '../contrail-targets/prod.js';\nexport const contrailTarget = 'prod' as const;\n`,
		'prod'
	);
	console.log('Contrail target: production (https://api.atmo.watch)');
}

function assertLoopbackEndpoint(endpoint) {
	const url = new URL(endpoint);
	if (!['127.0.0.1', 'localhost', '::1', '[::1]'].includes(url.hostname)) {
		throw new Error(`Local Contrail endpoint must be loopback, received ${endpoint}`);
	}
}

async function waitForLocalApi(endpoint) {
	const waitMs = Number(process.env.ATMO_LOCAL_API_WAIT_MS ?? 30_000);
	const deadline = Date.now() + waitMs;
	const discoveryUrl = `${endpoint}/.well-known/contrail`;

	while (Date.now() < deadline) {
		try {
			const response = await fetch(discoveryUrl, { signal: AbortSignal.timeout(1_500) });
			if (response.ok) return;
		} catch {
			// The local API may still be starting.
		}
		await new Promise((resolve) => setTimeout(resolve, 250));
	}

	throw new Error(
		`Local Contrail API did not become ready at ${endpoint}. Run "pnpm api:dev" first or use "pnpm dev:stack".`
	);
}

function run(command, args) {
	return new Promise((resolve, reject) => {
		const child = spawn(command, args, { cwd: root, stdio: 'inherit' });
		child.once('error', reject);
		child.once('exit', (code, signal) => {
			if (code === 0) resolve();
			else reject(new Error(`${command} exited with ${signal ?? `code ${code}`}`));
		});
	});
}

async function connectLocal(endpoint) {
	let update = false;
	try {
		const lock = JSON.parse(await readFile(localLockPath, 'utf8'));
		if (normalizeEndpoint(lock.endpoint) === endpoint) update = true;
		else await rm(localConsumerRoot, { recursive: true, force: true });
	} catch {
		await rm(localConsumerRoot, { recursive: true, force: true });
	}

	await mkdir(localConsumerRoot, { recursive: true });
	const contrailBin = path.join(
		root,
		'node_modules/.bin',
		process.platform === 'win32' ? 'contrail.cmd' : 'contrail'
	);
	const args = [
		'connect',
		endpoint,
		'--root',
		localConsumerRoot,
		'--out',
		'lexicons',
		'--lock',
		'contrail.lock.json',
		'--client',
		'index.ts',
		'--client-types',
		'types/index.ts',
		'--allow-insecure-http'
	];
	if (update) args.push('--update');
	await run(contrailBin, args);

	// The app's tracked API types represent the source tree. Reusing them avoids
	// loading a second set of ambient XRPC declarations from the ignored local bundle.
	const client = await readFile(localClientPath, 'utf8');
	const patchedClient = client.replace(
		'import type {} from "./types/index.js";',
		'import type {} from "../../src/lib/contrail/types/index.js";'
	);
	if (patchedClient === client) {
		throw new Error('Could not redirect the generated local Contrail client types');
	}
	await writeFile(localClientPath, patchedClient);
}

async function selectLocal() {
	const endpoint = normalizeEndpoint(process.env.ATMO_LOCAL_API_URL ?? defaultLocalEndpoint);
	assertLoopbackEndpoint(endpoint);
	await waitForLocalApi(endpoint);
	await connectLocal(endpoint);

	const lock = JSON.parse(await readFile(localLockPath, 'utf8'));
	const protectedMethods = (lock.serviceAuth?.methods ?? []).map((method) => method.id);
	const methods = [...new Set([...lock.methods, ...protectedMethods])].sort();
	await writeActiveModule(
		`// Generated by scripts/select-contrail.mjs. Do not edit.\nexport { contrail } from '../../../.contrail/local-consumer/index.js';\nexport const contrailMethods = ${JSON.stringify(methods, null, '\t')} as const;\nexport const contrailTarget = 'local' as const;\n`,
		'local'
	);
	console.log(`Contrail target: local (${endpoint})`);
}

export async function selectContrail(target = process.env.ATMO_API_TARGET ?? 'prod') {
	if (target === 'prod') return selectProd();
	if (target === 'local') return selectLocal();
	throw new Error(`Unknown Contrail target "${target}"; expected "prod" or "local"`);
}

const isMain =
	process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (isMain) {
	selectContrail(process.argv[2]).catch((cause) => {
		console.error(cause instanceof Error ? cause.message : cause);
		process.exitCode = 1;
	});
}
